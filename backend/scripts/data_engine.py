def _load_existing_alerts():
    if not os.path.exists(PATHS["alerts"]):
        return []
    try:
        with open(PATHS["alerts"], "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return []


# Official alerts from NDMA SACHET (IMD, CWC and the state SDMA publish CAP
# alerts there; no key). Only these issuing offices' alerts are downloaded, and
# each must name Telangana. See core/sachet.py.
SACHET_OFFICES = ("Telangana", "Hyderabad", "CWC", "New Delhi")


def _sachet_records(now_dt, kept, seen_titles):
    from core.alert_feed import build_official_record
    from core.sachet import AreaFilter, fetch_alerts

    session = requests.Session()
    session.headers["User-Agent"] = "telangana.live alerts (+https://www.telangana.live)"

    def get(url):
        response = session.get(url, timeout=30)
        response.raise_for_status()
        return response.text

    known = set()
    for alert in kept:
        match = re.search(r"sachet\.ndma\.gov\.in/.*identifier=([\w-]+)", alert.get("link") or "")
        if match:
            known.add(match.group(1))
    try:
        alerts = fetch_alerts(AreaFilter(state="Telangana"), offices=SACHET_OFFICES,
                              now=now_dt, get=get, skip_guids=known)
    except Exception as e:
        print(f"  ⚠️ SACHET feed unavailable: {e}")
        return []

    records = []
    for alert in alerts:
        record = build_official_record(alert, now=now_dt)
        if record["title"] in seen_titles:
            continue
        seen_titles.add(record["title"])
        records.append(record)
    print(f"  ✅ SACHET: {len(records)} new official alert(s)")
    return records


def sync_alerts():
    """Scan Google News RSS for likely local civic disruptions (floods, power/water
    outages, road closures, strikes, weather warnings) and write a deduped,
    auto-expiring alerts feed to frontend/src/data/alerts.json.

    Geographic scoping: queries are state-wide (not per-district — Telangana.live
    isn't multi-district-routed like the reference implementation this pattern was
    scoped from), and each match is regionally tagged using the existing
    core.news_classifier.classify_article() region inference instead of a new
    per-district query loop.
    """
    print("Syncing local alerts feed...")

    now_dt = datetime.datetime.now(datetime.timezone.utc)
    kept, existing_titles = partition_existing(
        _load_existing_alerts(), now=now_dt, expiry_days=ALERT_EXPIRY_DAYS)

    new_alerts = []
    rejected = 0
    stale = 0

    for query in ALERT_TOPIC_QUERIES:
        try:
            rss_url = f"https://news.google.com/rss/search?q={requests.utils.quote(query)}&hl=en-IN&gl=IN&ceid=IN:en"
            feed = feedparser.parse(rss_url)
        except Exception as e:
            print(f"  ⚠️ Alert query failed ({query!r}): {e}")
            continue

        for entry in feed.entries[:10]:
            title = entry.get("title", "").strip()
            # Google News RSS appends " - Source Name" to titles; strip it so the
            # outlet's own name can't be read as part of the reported event.
            headline_only = re.sub(r"\s+-\s+[^-]+$", "", title)
            description_raw = entry.get("summary", "").strip()
            description = html.unescape(re.sub(r"<[^>]+>", "", description_raw)).strip()
            if not title or title in existing_titles:
                continue
            existing_titles.add(title)  # the same story often answers several queries

            # Google News search returns articles years old; drop them before
            # spending a triage call. The headline alone can't tell their age.
            if not is_fresh(entry.get("published_parsed"), now=now_dt,
                            max_age_days=ALERT_EXPIRY_DAYS):
                stale += 1
                continue

            if not triage_headline:
                continue

            # One request answers all four: which disruption type (or none),
            # whether it is in Telangana, whether it is current, how severe.
            verdict = triage_headline(headline_only, description)
            if not verdict.accepted:
                rejected += 1
                continue

            keyword_region = None
            if classify_article:
                _, keyword_region = classify_article(title, description)
            region = district_for(verdict, keyword_region=keyword_region)

            source = entry.get("source")
            new_alerts.append(build_alert_record(
                title=title,
                description=description,
                alert_type=verdict.alert_type,
                severity=verdict.severity,
                district=region,
                link=entry.get("link", ""),
                source=source.get("title", "Google News RSS") if isinstance(source, dict) else "Google News RSS",
                published=entry.get("published_parsed"),
                now=now_dt,
            ))

    official = _sachet_records(now_dt, kept, existing_titles)
    all_alerts = kept + official + new_alerts
    with open(PATHS["alerts"], "w", encoding="utf-8") as f:
        json.dump(all_alerts, f, indent=2, ensure_ascii=False)

    if os.path.exists(os.path.dirname(PATHS["alerts_public"])):
        with open(PATHS["alerts_public"], "w", encoding="utf-8") as f:
            json.dump(all_alerts, f, indent=2, ensure_ascii=False)
    else:
        # BreakingNewsBanner fetches this copy at runtime; skipping it silently
        # is how the public feed went unwritten before.
        print(f"  ⚠️ Public alerts dir missing, not written: {os.path.dirname(PATHS['alerts_public'])}")

    print(f"  ✅ Synced {len(new_alerts)} new alerts, rejected {rejected}, stale {stale} (Total active: {len(all_alerts)})")
    return all_alerts


