# Top-level keys that change on every run without the data changing.
_VOLATILE_KEYS = ("updatedAt", "lastUpdated", "generatedAt")


def _comparable(data):
    if isinstance(data, dict):
        return {k: v for k, v in data.items() if k not in _VOLATILE_KEYS}
    return data


def _unchanged(path, data):
    """True when the file already holds this data, ignoring run timestamps."""
    try:
        with open(path, encoding="utf-8") as f:
            match = re.search(r"= (\{[\s\S]*\}|\[[\s\S]*\]);\s*$", f.read())
        return bool(match) and _comparable(json.loads(match.group(1))) == _comparable(data)
    except (OSError, ValueError):
        return False


def _write_module(path, header, var_name, data):
    """Write a JS data module unless only its timestamps would change.

    Every run used to rewrite the file with a new run time, so every
    scheduled sync committed and redeployed even when no value changed
    (TL-08). Returns True when the file was written.
    """
    if _unchanged(path, data):
        print(f"  = Unchanged: {path}")
        return False
    js = f"{header}\nexport const {var_name} = {json.dumps(data, indent=2, ensure_ascii=False)};\n"
    with open(path, "w", encoding="utf-8") as f:
        f.write(js)
    return True


def write_js(filename, var_name, data):
    path = os.path.join(DATA_DIR, filename)
    written = _write_module(path, f"// Auto-generated by data_engine.py — {NOW}", var_name, data)
    if written:
        print(f"  ✅ Written: {path}")
    return written


def write_js_module(path, var_name, data):
    """Writes directly to the given path (used by the sync functions and tests)."""
    return _write_module(path, f"// Automatically generated by data_engine.py at {NOW}", var_name, data)


def get_recent_news_for_entity(entity_type: str, entity_id: str, limit: int = 5) -> list:
    """Reads news.json and returns a list of recent articles matching the entity_type and entity_id."""
    news_path = PATHS["news"]
    if not os.path.exists(news_path):
        return []
    try:
        with open(news_path, "r", encoding="utf-8") as f:
            articles = json.load(f)
        matches = []
        for article in articles:
            correlated = article.get("correlated_civic_entities", [])
            for ent in correlated:
                if ent.get("entity_type") == entity_type and ent.get("entity_id") == entity_id:
                    matches.append({
                        "id": article.get("id"),
                        "title": article.get("title"),
                        "description": article.get("description"),
                        "link": article.get("link"),
                        "source": article.get("source"),
                        "published": article.get("published"),
                        "category": article.get("category"),
                        "region": article.get("region"),
                        "image_url": article.get("image_url"),
                        "ai_summary": article.get("ai_summary")
                    })
                    break
        return matches[:limit]
    except Exception as e:
        print(f"  ⚠️ Error reading news for correlations: {e}")
        return []


