def write_js(filename, var_name, data):
    path = os.path.join(DATA_DIR, filename)
    js = f"// Auto-generated by data_engine.py — {NOW}\nexport const {var_name} = {json.dumps(data, indent=2, ensure_ascii=False)};\n"
    with open(path, "w", encoding="utf-8") as f:
        f.write(js)
    print(f"  ✅ Written: {path}")


def write_js_module(path, var_name, data):
    """Alias used by tests — writes directly to the given path."""
    js = f"// Automatically generated by data_engine.py at {NOW}\nexport const {var_name} = {json.dumps(data, indent=2, ensure_ascii=False)};\n"
    with open(path, "w", encoding="utf-8") as f:
        f.write(js)


