def sync_to_redis(key, data):
    from dotenv import load_dotenv
    load_dotenv(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".env"))
    
    redis_url = os.environ.get("UPSTASH_REDIS_REST_URL")
    redis_token = os.environ.get("UPSTASH_REDIS_REST_TOKEN")
    
    if not redis_url or not redis_token:
        print(f"  ℹ️ Upstash credentials absent, skipped syncing {key} to Redis.")
        return
        
    try:
        url = f"{redis_url.rstrip('/')}/set/{key}"
        headers = {"Authorization": f"Bearer {redis_token}"}
        resp = requests.post(url, headers=headers, json=data)
        resp.raise_for_status()
        print(f"  ✅ Synced {key} to Upstash Redis directly!")
    except Exception as e:
        print(f"  ⚠️ Redis sync failed for {key}: {e}")



def clean_price(value):
    value = str(value).strip()
    value = value.replace("Rs.", "").replace("Rs", "").replace("₹", "").replace(",", "").strip()
    m = re.search(r"(\d+(?:\.\d+)?)", value)
    if not m:
        return None
    num = m.group(1)
    if "." in num:
        return f"₹{float(num):.2f}"
    return f"₹{num}"


