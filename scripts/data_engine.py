# --- Utils ---
def write_js_module(path, var_name, data):
    """Writes a dictionary as an ES module constant."""
    content = f"// Automatically generated by data_engine.py at {datetime.now().isoformat()}\n"
    content += f"export const {var_name} = {json.dumps(data, indent=2, ensure_ascii=False)};\n"
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)

def clean_html(raw_html):
    if not raw_html: return ""
    return re.sub('<.*?>', '', raw_html).strip()

def get_ai_summary(title, description):
    if not model: return ""
    prompt = f"Summarize this news article in exactly 2 concise lines for a civic portal. Title: {title}. Description: {description}"
    try:
        response = model.generate_content(prompt)
        return response.text.strip()
    except Exception as e:
        print(f"AI Error: {e}")
        return ""

